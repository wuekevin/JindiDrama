import { test, expect } from './fixtures'
test.describe('09 账号登录', () => {
  test.beforeEach(async ({ page }) => { await page.goto('/#/login'); await page.evaluate(() => localStorage.removeItem('jindi.auth.v1')); await page.reload(); await page.waitForSelector('[data-testid=page-login]') })
  test('screenshot + demo badge visible (no official-login claim)', async ({ page }) => { await expect(page.getByTestId('demo-badge')).toContainText('演示模式'); await expect(page.locator('body')).not.toContainText('红果账号登录'); await page.screenshot({ path: '../design/rendered/09-账号登录.png' }) })
  test('validation: empty submit shows all errors', async ({ page }) => { await page.getByTestId('submit').click(); await expect(page.getByTestId('err-phone')).toBeVisible(); await expect(page.getByTestId('err-code')).toBeVisible(); await expect(page.getByTestId('err-agree')).toBeVisible() })
  test('opens the bundled privacy notice offline before login without confirming', async ({ page }) => {
    await page.context().setOffline(true)
    const trigger = page.getByRole('button', { name: '《隐私说明》' })
    await trigger.click({ timeout: 3000 })
    const dialog = page.getByRole('dialog', { name: '金帝短剧隐私说明' })
    await expect(dialog).toContainText('演示登录不会发送短信')
    await expect(dialog).toContainText('并发送为该片源输入的搜索词以获取结果')
    await expect(dialog).toContainText('应用不会向片源同步本机观看历史、收藏、搜索历史')
    await expect(dialog.getByText('适用范围', { exact: false })).toBeFocused()
    await page.screenshot({ path: '../design/rendered/09-演示登录隐私说明.png' })
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
    await expect(page.getByTestId('agree')).not.toBeChecked()
    await expect(page.getByTestId('logged-in')).toHaveCount(0)
  })
  test('invalid phone blocks get-code; valid starts countdown', async ({ page }) => {
    await page.getByTestId('phone').fill('123'); await page.getByTestId('get-code').click(); await expect(page.getByTestId('err-phone')).toBeVisible()
    await page.getByTestId('phone').fill('13800138000'); await page.getByTestId('get-code').click(); await expect(page.getByTestId('get-code')).toContainText('重新获取('); await expect(page.getByTestId('get-code')).toBeDisabled()
  })
  test('wrong code counts down attempts then locks', async ({ page }) => {
    await page.getByTestId('phone').fill('13800138000'); await page.getByTestId('agree').check()
    for (let i = 4; i >= 0; i--) { await page.getByTestId('code').fill('000000'); await page.getByTestId('submit').click(); await expect(page.getByTestId('err-form')).toContainText(i > 0 ? `还可尝试 ${i} 次` : '尝试次数过多') }
    await expect(page.getByTestId('submit')).toBeDisabled()
  })
  test('correct demo code → demo session, logout returns to form', async ({ page }) => {
    await page.getByTestId('phone').fill('13800138000'); await page.getByTestId('code').fill('123456'); await page.getByTestId('agree').check(); await page.getByTestId('submit').click()
    await expect(page.getByTestId('logged-in')).toContainText('演示用户8000'); await page.reload(); await expect(page.getByTestId('logged-in')).toBeVisible()
    await page.getByTestId('logout').click(); await expect(page.getByTestId('phone')).toBeVisible()
  })
  test('withdrawing confirmation or opening the notice cancels an in-flight phone login', async ({ page }) => {
    await page.clock.install()
    await page.getByTestId('phone').fill('13800138000')
    await page.getByTestId('code').fill('123456')
    const confirmation = page.getByTestId('agree')
    const submit = page.getByTestId('submit')
    await confirmation.check()
    await submit.click()
    await confirmation.uncheck()
    await page.clock.fastForward(500)
    await expect(page.getByTestId('err-agree')).toBeVisible()
    await expect(page.getByTestId('logged-in')).toHaveCount(0)
    await confirmation.check()
    await submit.click()
    await page.getByRole('button', { name: '《隐私说明》' }).click()
    await page.clock.fastForward(500)
    await expect(page.getByRole('dialog', { name: '金帝短剧隐私说明' })).toBeVisible()
    await expect(page.getByTestId('logged-in')).toHaveCount(0)
  })
  test('qr state machine: waiting → scanned → confirmed', async ({ page }) => {
    await page.getByTestId('tab-qr').click(); await expect(page.getByTestId('sim-confirm')).toBeDisabled(); await page.getByTestId('sim-scan').click(); await expect(page.getByTestId('qr-overlay')).toContainText('已扫码')
    await page.getByTestId('sim-confirm').click()
    await expect(page.getByTestId('err-agree')).toContainText('隐私说明')
    await expect(page.getByTestId('logged-in')).toHaveCount(0)
    await page.getByTestId('agree').check()
    await expect(page.getByTestId('err-agree')).toHaveCount(0)
    await page.getByTestId('sim-confirm').click(); await expect(page.getByTestId('logged-in')).toBeVisible()
    await page.getByTestId('logout').click()
    await expect(page.getByTestId('agree')).not.toBeChecked()
    await expect(page.getByTestId('sim-scan')).toBeEnabled()
  })
  test('qr expiry and refresh', async ({ page }) => { await page.getByTestId('tab-qr').click(); await page.getByTestId('sim-expire').click(); await expect(page.getByTestId('qr-overlay')).toContainText('已过期'); await page.getByTestId('qr-refresh').click(); await expect(page.getByTestId('qr-overlay')).toHaveCount(0) })
  test('session expired banner', async ({ page }) => { await page.goto('/#/login?state=expired'); await expect(page.getByTestId('expired')).toContainText('已过期') })
  test('keyboard: Enter submits form', async ({ page }) => { await page.getByTestId('phone').focus(); await page.keyboard.press('Enter'); await expect(page.getByTestId('err-phone')).toBeVisible() })
  test('avatar opens login', async ({ page }) => { await page.goto('/#/home?static'); await page.getByTestId('avatar').click(); await expect(page).toHaveURL(/#\/login/) })
  for (const [w, h] of [[1366, 768], [1920, 1080], [2560, 1440]]) test(`responsive ${w}`, async ({ page }) => { await page.setViewportSize({ width: w, height: h }); await page.reload(); await page.waitForSelector('[data-testid=page-login]'); expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)).toBe(false); await page.screenshot({ path: `../design/rendered/responsive/09-${w}x${h}.png` }) })
})

for (const dpi of [150, 220]) {
  test(`offline demo login controls stay reachable at ${dpi}% zoom`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width: 1280, height: 860 })
    await page.addInitScript((zoom) => {
      localStorage.setItem('jindi.settings.v1', JSON.stringify({ theme: 'light', dpi: zoom }))
    }, dpi)
    await page.goto('/#/login')
    const login = page.getByTestId('page-login')
    const codeButton = login.getByTestId('get-code')
    await expect(codeButton).toBeVisible()
    async function checkForm() {
      const clipped = await login.evaluate((root) => {
        const local = root.getBoundingClientRect()
        return [...root.querySelectorAll('button, input, header [data-testid=demo-badge]')].flatMap(el => {
          const box = el.getBoundingClientRect()
          return box.width && (box.x < local.x - 1 || box.right > local.right + 1) ? [el.getAttribute('data-testid') ?? el.textContent] : []
        })
      })
      expect(clipped).toEqual([])
    }
    await checkForm()
    await expect(login.getByTestId('demo-badge')).toHaveCSS('color', 'rgb(117, 81, 21)')
    await page.screenshot({ path: testInfo.outputPath('phone.png') })
    await page.context().setOffline(true)
    const trigger = login.getByRole('button', { name: '《隐私说明》' })
    await trigger.press('Enter')
    const dialog = page.getByRole('dialog', { name: '金帝短剧隐私说明' })
    await expect(dialog).toContainText('演示登录不会发送短信')
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await expect(login.getByTestId('agree')).not.toBeChecked()
    await login.getByTestId('phone').fill('13800138000')
    await codeButton.click()
    await expect(codeButton).toBeDisabled()
    const codeNotice = page.getByTestId('toast').filter({ hasText: '验证码为' })
    await expect(codeNotice).toBeVisible()
    await expect(codeNotice).toHaveCSS('color', 'rgb(246, 236, 233)')
    const demoCode = (await codeNotice.innerText()).match(/验证码为 (\d{6})/)?.[1]
    expect(demoCode).toBeDefined()
    await checkForm()
    await login.getByTestId('agree').check()
    const code = login.getByTestId('code')
    await code.fill(demoCode!)
    await code.press('Enter')
    await expect(login.getByTestId('logged-in')).toContainText('演示用户8000')
    await expect(login.getByRole('heading', { name: '演示用户8000' })).toBeFocused()
    await checkForm()
    await login.getByTestId('logout').click()

    const phoneTab = login.getByRole('tab', { name: '手机号登录' })
    const qrTab = login.getByRole('tab', { name: '扫码登录' })
    await expect(phoneTab).toBeFocused()
    await page.keyboard.press('ArrowRight')
    await expect(qrTab).toBeFocused()
    await page.keyboard.press('Home')
    await expect(phoneTab).toBeFocused()
    await login.getByRole('button', { name: '切换到扫码登录' }).press('Enter')
    await expect(qrTab).toBeFocused()
    const qr = login.getByTestId('qr-panel')
    await expect(qr).toBeVisible()
    await expect(qr.locator('.qr')).toHaveCSS('background-color', 'rgb(38, 23, 25)')
    await checkForm()
    await qr.getByTestId('sim-expire').click()
    await qr.getByTestId('qr-refresh').press('Enter')
    await expect(qr.getByTestId('sim-scan')).toBeFocused()
    await qr.getByTestId('sim-scan').click()
    await expect(qr.getByTestId('qr-overlay')).toContainText('已扫码')
    await page.screenshot({ path: testInfo.outputPath('qr.png') })
    await login.getByTestId('agree').check()
    await qr.getByTestId('sim-confirm').press('Enter')
    await expect(login.getByTestId('logged-in')).toContainText('本地演示会话')
    await checkForm()
    await login.getByTestId('logout').press('Enter')
    await expect(qr.getByTestId('sim-scan')).toBeEnabled()
    await expect(qrTab).toBeFocused()
  })
}
